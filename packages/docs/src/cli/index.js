#!/usr/bin/env node
import { Command } from "commander";
import { cosmiconfig } from "cosmiconfig";
import path from "node:path";
import fs from "node:fs/promises";

const program = new Command();
program.name("apidocs").description("Apipuccino apidocs — offline OpenAPI docs generator").version("2.0.0");

program.command("init").description("scaffold apidocs.config.js + example openapi.yaml").action(async () => {
  const cfg = `/** @type {import('@apipuccino/docs').ApidocsConfig} */\nexport default { input: "./openapi.yaml", output: "./api-docs", theme: "default" };\n`;
  await fs.writeFile("apidocs.config.js", cfg, { flag: "wx" }).catch(()=>console.log("apidocs.config.js already exists"));
  console.log("✓ apidocs init done — edit apidocs.config.js and run: npx apidocs build");
});

program.command("build").description("build static docs").option("-i, --input <path>", "openapi file or glob").option("-o, --output <dir>", "output dir").option("-t, --theme <name>", "theme default|dark|monokai|nord").option("--pdf-advanced", "generate PDF via puppeteer-core (optional)").action(async (opts) => {
  const explorer = cosmiconfig("apidocs");
  const found = await explorer.search();
  const cfg = { input: "./openapi.yaml", output: "./api-docs", theme: "default", ...found?.config, ...opts };
  console.log("Building with config:", cfg);
  // TODO: wire parser -> generator -> search (Day 2-3)
  const { parseSpec } = await import("../parser/index.js");
  const { generatePages } = await import("../generator/index.js");
  const { buildSearchIndex } = await import("../search/index.js");
  const { versionedOutputs } = await import("../utils/version-switcher.js");
  const outputs = versionedOutputs(cfg);
  for (const { input, output } of outputs) {
    console.log(`→ building ${input} → ${output}`);
    const spec = await parseSpec(input);
    await generatePages(spec, { ...cfg, output });
    await buildSearchIndex(output);
  }
  cfg.output = outputs[0].output; // for pdf step
  console.log(`✓ built to ${cfg.output}`);
  if (opts.pdfAdvanced) {
    console.log("⚠ --pdf-advanced uses puppeteer-core + @sparticuz/chromium (adds ~100MB) — run manually if needed");
    const { generatePDF } = await import("../pdf/index.js");
    await generatePDF(cfg.output);
  }
});

program.command("serve").description("preview output").option("-o, --output <dir>", "output dir", "./api-docs").action(async (opts) => {
  console.log(`Serving ${opts.output} — use: npx serve ${opts.output} or python -m http.server --directory ${opts.output}`);
});

program.command("submit").description("submit current API to Apipuccino directory (creates PR)").option("--dry-run", "prepare entry without pushing PR").action(async (opts) => {
  const explorer = cosmiconfig("apidocs");
  const found = await explorer.search();
  const cfg = { input: "./openapi.yaml", output: "./api-docs", ...found?.config };
  console.log("Reading", cfg.input);
  const { parseSpec } = await import("../parser/index.js");
  const spec = await parseSpec(cfg.input);
  // Derive probe from servers[0] or first path
  const baseUrl = spec.servers?.[0]?.url || `https://${spec.info.title.toLowerCase().replace(/[^a-z0-9]+/g,"-")}.example.com`;
  const slug = spec.info.title.toLowerCase().replace(/[^a-z0-9]+/g,"-").slice(0,48);
  const entry = {
    name: spec.info.title,
    slug,
    url: baseUrl,
    probe: { method: "GET", expectedStatus: 200, expectedContentType: "application/json", timeoutMs: 8000 },
    auth: spec.components?.securitySchemes ? "key" : "none",
    category: (spec.tags?.[0]?.name || "general").toLowerCase(),
    cors: "unknown",
    docs: baseUrl,
    openapiUrl: cfg.input.toString().startsWith("http") ? cfg.input.toString() : undefined,
    added: new Date().toISOString().slice(0,10),
  };
  console.log("Prepared entry:\n" + JSON.stringify(entry, null, 2));
  // Verify build
  const { generatePages } = await import("../generator/index.js");
  // dry build to temp
  if (!opts.dryRun) {
    // Append to apis.json and create PR via gh
    const apisPath = path.resolve("packages/directory/data/apis.json");
    let apis = [];
    try { apis = JSON.parse(await fs.readFile(apisPath,"utf8")); } catch {}
    if (apis.find(a=>a.slug===slug)) { console.error(`✗ slug ${slug} already exists`); process.exit(1); }
    apis.push(entry);
    await fs.writeFile(apisPath, JSON.stringify(apis, null, 2)+"\n");
    console.log(`✓ appended to ${apisPath}`);
    // Try gh CLI
    try {
      const { execSync } = await import("node:child_process");
      execSync(`gh pr create --title "feat: add ${entry.name}" --body "Verified with apidocs build — ${spec.info.title} v${spec.info.version}\n\nProbe: ${entry.url}\n\nAuto-generated by \`npx apidocs submit\`" --label apipuccino`, { stdio: "inherit" });
    } catch (e) {
      console.log("→ gh not installed or not authenticated. Manually: git checkout -b add/"+slug+" && git commit -am 'feat: add "+slug+"' && gh pr create");
    }
  } else {
    console.log("(dry-run — not writing apis.json)");
  }
});

program.command("check").description("probe your own API using same checker (L0/L1)").option("--url <url>", "API URL to probe").action(async (opts) => {
  const url = opts.url || "http://localhost:3000/health";
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(8000) });
    console.log(`${res.status} ${res.statusText} — ${res.headers.get("content-type")}`);
    console.log(res.ok ? "✓ LIVE" : "✗ FAIL");
  } catch (e) { console.error("✗", e.message); process.exit(1); }
});

program.parse();
